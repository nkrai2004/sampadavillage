(function () {
  var STORAGE_KEY = "sampada_lang";
  var originals = null; // captured once: [{el, text}] and [{el, attr, value}]

  function captureOriginals() {
    originals = { text: [], attrs: [] };
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      originals.text.push({ el: el, text: el.textContent });
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      originals.attrs.push({ el: el, attr: "placeholder", value: el.getAttribute("placeholder") });
    });
  }

  function applyLang(lang) {
    if (!originals) captureOriginals();
    document.documentElement.lang = lang;

    if (lang === "hi") {
      originals.text.forEach(function (item) {
        var key = item.el.getAttribute("data-i18n");
        if (SAMPADA_HI[key] !== undefined) item.el.textContent = SAMPADA_HI[key];
      });
      originals.attrs.forEach(function (item) {
        var key = item.el.getAttribute("data-i18n-placeholder");
        if (SAMPADA_HI[key] !== undefined) item.el.setAttribute(item.attr, SAMPADA_HI[key]);
      });
    } else {
      originals.text.forEach(function (item) { item.el.textContent = item.text; });
      originals.attrs.forEach(function (item) { item.el.setAttribute(item.attr, item.value); });
    }

    document.querySelectorAll(".lang-toggle button").forEach(function (btn) {
      btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    });
  }

  function initLang() {
    captureOriginals();
    var saved = localStorage.getItem(STORAGE_KEY) || "en";
    applyLang(saved);

    document.querySelectorAll(".lang-toggle button").forEach(function (btn) {
      btn.addEventListener("click", function () {
        var lang = btn.getAttribute("data-lang");
        localStorage.setItem(STORAGE_KEY, lang);
        applyLang(lang);
      });
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initLang);
  } else {
    initLang();
  }
})();
